const normaliseCity = (value) => (value ?? "").toLowerCase().replace(/[^a-z]/g, "");

export function findCity(name) {
  const key = normaliseCity(name);
  if (!key) return null;
  return (
    DESTINATIONS.find((d) => normaliseCity(d.city) === key) ??
    DESTINATIONS.find((d) => key.startsWith(normaliseCity(d.city))) ??
    null
  );
}
